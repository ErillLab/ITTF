# -*- coding: utf-8 
"""
Performs Information Degradation experiment

Loads in motifPopulation generated from fitMotifPopulation.py from  inputted file path, 
mutates motifs, measures Information/Divergence after each generation of mutation, and 
outputs statistics to csv file
"""
import json
import csv
from scipy.stats import sem
from src.helperFunctions import reachedAsymptote, ComputeAverageJSD
from src.Objects.motifpopulation import MotifPopulation
from copy import deepcopy
from statistics import mean

def updateLossDict(organismList, lossDict, frozenMotifList,motifLength, generationNum):
    """
    Helper function for simulation. Updates lossDict with statistics 
    about mean/stdev Information and Divergence in the population

    """
    Average_IC = mean([obj.IC for obj in organismList])
    SEM_IC = sem([obj.IC for obj in organismList])
    
    Average_MI = mean([obj.MI for obj in organismList])
    SEM_MI = sem([obj.MI for obj in organismList])
    
    Average_TI = mean([obj.TI for obj in organismList])
    SEM_TI = sem([obj.TI for obj in organismList])
    
    #Computes JSD of each organism against its original motif
    JSDlist = ComputeAverageJSD(frozenMotifList,[obj.TFBS for obj in organismList],motifLength)
    
    Average_JSD = mean(JSDlist)
    SEM_JSD = sem(JSDlist)
    
    #Adds to lossDict
    lossDict["# Generation after mutation"].append(generationNum)
    lossDict["IC"].append(Average_IC); lossDict["SEM_IC"].append(SEM_IC)
    lossDict["MI"].append(Average_MI); lossDict["SEM_MI"].append(SEM_MI)
    lossDict["TI"].append(Average_TI); lossDict["SEM_TI"].append(SEM_TI)
    lossDict["JSD"].append(Average_JSD); lossDict["SEM_JSD"].append(SEM_JSD)

def main():
    #Opens the json file and reads
    with open("./src/settings_informationDecay.json") as jfile:
        json_file = json.load(jfile)
        
    #Grabs population file paths
    populationFile = json_file["Population_File"]
    
    #Loads json input dealing with loss of information of population and num_generations in output file
    numGenerationsTerminate = json_file["NumGenerationTerminate"]
    outputCSV = json_file["lossOutputCSV"]
        
    #Loads population from input file path
    motifPop = MotifPopulation(importPath= populationFile)
    
    #Prepares list containing sublists with the elements in fields 
    #Note: JSD/SEM_JSD returns 1 with motifs longer than 2bps
    lossDict = {"# Generation after mutation":[], "IC":[], "MI":[], "TI":[], "SEM_IC":[], "SEM_MI":[], "SEM_TI":[],
                "JSD":[], "SEM_JSD":[]}
    
    #Saves original motif for computing divergence
    frozenMotifList = deepcopy([obj.TFBS for obj in motifPop.population_list])
    fields = list(lossDict.keys())
    
    motifLength = motifPop.population_list[0].length_bs
    
    
    #Counter variable for appending to lossList
    generationNum = 0

    
    #Runs until each generation reaches asymptote of TI
    if numGenerationsTerminate is None:
        while (not reachedAsymptote(lossDict["TI"])):
            #Calculates Average IC, MI, and TI of population and appends to lossDict
            updateLossDict(motifPop.population_list, lossDict,
                           frozenMotifList,motifLength, generationNum)
            
            #Mutates organism lines, updating Average IC, MI, and TI
            motifPop.Lose_Information2()
            
            #Adds to generationNum
            generationNum += 1
            
    #Runs for a select number of generations
    else:
        while (generationNum <= numGenerationsTerminate):
            #Calculates Average IC, MI, and TI of population and appends to lossDict
            updateLossDict(motifPop.population_list, lossDict,
                           frozenMotifList,motifLength, generationNum)
            
            #Mutates organism lines, updating Average IC, MI, and TI
            motifPop.Lose_Information2()
            
            #Adds to generationNum
            generationNum += 1
        
    
    #Prints to csv file
    with open(outputCSV, "w", newline = "") as outputcsv:
        csvwriter = csv.writer(outputcsv)
        
        #Write fields
        csvwriter.writerow(fields)
        
        #Writes list
        for i in range(len(lossDict["# Generation after mutation"])):
            csvwriter.writerow([lossDict[stat][i] for stat in list(lossDict.keys())])
          
    

    #Generates output variable if populationFile is not given
    #if populationDecayFile:
        #motifPop._export(populationDecayFile)
        
        
    
if __name__ == "__main__":
    '''
    Json parameters:
        populationFile: str 
            Path to json file generated by fitMotifPopulation.py
                    
        numGenerationsTerminate: int or null
            Number of generations to run information decay. 
            Null will run simulation until an asymptotic TI value is reached
        
        outputCSV: str
            Path to output statistics about the population after each generation of mutation (information decay)
    '''
    main()
    
    