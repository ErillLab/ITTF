import csv 
import json
from sklearn import metrics
from src.Objects.motifpopulation import MotifPopulation
from src.Objects.genome import Genome, scoreGenome
from src.helperFunctions import create_dipwm_object
        

# XXX

if __name__ == "__main__":
    """
    Json parameters:
        populationFile: str 
            Path to json file generated by fitMotifPopulation.py
                    
        numGenerationsTerminate: int or null
            Number of generations to run information decay. Null will run simulation until an asymptotic value is reached
        
        outputCSV: str
            Path to output statistics about the population after each generation of mutation (information decay)
    
    """
    with open("./src/settings_GenomeExperiment.json") as jfile:
        json_file = json.load(jfile)
        
    #Grabs population file paths
    populationFile = json_file["Population_File"]
    
    #Loads json input dealing with loss of information of population and num_generations in output file
    numGenerationsTerminate = json_file["NumGenerationTerminate"]
    outputCSV = json_file["lossOutputCSV"]
    
    #Loads json input specificalyl for genome experiment
    genomeLength = json_file["genomeLength"]   
    
    #Loads population from input file path
    motifPop = MotifPopulation(importPath= populationFile)
    

    #Initializes list this will contain average AUC of population at each generation
    AUClist = []
    
    #Initializes 2D list with the AUC after successive mutations for each organism
    organismAUCListCollection = []
    
    #Assembles genome, computes PR curve, and induces mutations for each organism in population
    for organism in motifPop.population_list:
        
        #List of AUC after mutation for an organism
        organismAUCList = []
        
        #Grabs binding sites
        bindingSites = organism.TFBS
        
        #Creates genome object from random letters and binding sites
        genomeObj = Genome(genomeSize = genomeLength, motif_numberBS = 0, lengthBS = len(bindingSites[0]),
                        numBS = len(bindingSites), readinBS = bindingSites) 
        
        #Reads motif as frozen set of TFBS
        diP = create_dipwm_object(organism.TFBS)
        
        #Creates positive negative list describing each index of the genome as a positive or negative
        PNlist = [1 if i in genomeObj.indicesBS else 0 for i in range(genomeLength)] #Length of genome. Contains 1 for a position that is a binding site and 0 for a non binding site
    
        #Measures AUC and mutates        
        for i in range(numGenerationsTerminate):
            
            #Scores all positions in genome 
            scoresList =  scoreGenome(diP, len(bindingSites[0]), genomeObj.getCircularGenome())
                        
            #The TF can be described as a classifier of positives and negatives of potential binding sites
            #We use the skilearn Precision, recall functions to quantify how good the classifer is 
            precisionArray, recallArray, thresholds = metrics.precision_recall_curve(PNlist, scoresList)
        
            #Computes AUC as an indicator of how good of a job the TF does
            organismAUCList.append(metrics.auc(recallArray, precisionArray))
            
            #Induces mutation
            genomeObj.induceMutation()
        
        #Adds list of AUC of organism to 2D list
        organismAUCListCollection.append(organismAUCList)
        
        print("Completed one organism")
       
        
    
    #After all organisms have been genome searched, averages AUC at each generation of mutation and creates final, averaged AUC list
    for i in range(numGenerationsTerminate):
        sumAUC = 0
        
        #Iterates through each list to get AUC at specific generation
        for auclist in organismAUCListCollection:
            sumAUC += auclist[i]
        
        #Goes from sum to average
        meanAUC = sumAUC/len(motifPop.population_list)
        
        #Appends to list
        AUClist.append(meanAUC)
        

    
    #Writes AUClist to file
    with open(outputCSV, mode = "w", newline = '') as output:
        csvwriter = csv.writer(output)
        csvwriter.writerow(["Generation", "AUC"]) #Writes names of columns
        
        #Writes generation and AUC 
        for i in range(len(AUClist)):
            csvwriter.writerow([i, AUClist[i]])
        
        


        
        
