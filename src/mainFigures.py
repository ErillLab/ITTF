def Figure5(panelA_path="./Figure5A.png",
            inputDir="./Output/GPM",
            outputDir=OUTPUT_DIR + "Mekasha_Mascolo_Erill_2025_Fig5.pdf"):
    """
    Figure 5: Epistasis examples and GPM landscape analysis.
    Panel A: epistasis diagram (image). Panel B: GPM boxplots/histograms.
    """
    df_2bp = pd.read_csv(inputDir + "/2bp_motifs/GPM_analysis_2bp.csv")
    df_6bp = pd.read_csv(inputDir + "/6bp_motifs/GPM_analysis_6bp.csv")

    img = mpimg.imread(panelA_path)
    if img.max() > 1.0:
        img = img.astype(np.float32) / 255.0

    col_mean = img[:, :, :3].mean(axis=(0, 2))
    non_white = np.where(col_mean < 0.98)[0]
    left_crop = int(non_white[0]) if len(non_white) > 0 else 0
    img = img[:, left_crop:, :]

    fig_width = 12
    a_ratio = 4
    total_height = 18

    fig = plt.figure(figsize=(fig_width, total_height))
    gs = GridSpec(4, 2, figure=fig, height_ratios=[a_ratio, 1, 1, 1], hspace=0.15, wspace=0.15)

    ax_img = fig.add_subplot(gs[0, :])
    ax_img.imshow(img, aspect='auto')
    ax_img.axis("off")
    ax_img.text(-0.02, 1.05, "A", transform=ax_img.transAxes,
                fontsize=16, fontweight="bold", va="top")

    axs = np.array([[fig.add_subplot(gs[row, col]) for col in range(2)] for row in range(1, 4)])

    src.figureFunctions.generate_boxplots_new_mapanalysis(df_2bp, 'FDC_r',   plt_ax=axs[0, 0], ylabel='FDC')
    src.figureFunctions.generate_boxplots_new_mapanalysis(df_2bp, 'GDPDC_r', plt_ax=axs[1, 0], ylabel='GDPDC')
    src.figureFunctions.generate_histograms_for_NO_new_mapanalysis(df_2bp,   plt_ax=axs[2, 0])

    src.figureFunctions.generate_boxplots_new_mapanalysis(df_6bp, 'FDC_r',   plt_ax=axs[0, 1], ylabel='FDC')
    src.figureFunctions.generate_boxplots_new_mapanalysis(df_6bp, 'GDPDC_r', plt_ax=axs[1, 1], ylabel='GDPDC')
    src.figureFunctions.generate_histograms_for_NO_new_mapanalysis(df_6bp,   plt_ax=axs[2, 1])

    for ax in axs.flat:
        ax.grid(False)

    axs[0, 0].set_title("L = 2", fontsize=14)
    axs[0, 1].set_title("L = 6", fontsize=14)

    axs[0, 0].text(-0.18, 1.08, "B", transform=axs[0, 0].transAxes,
                   fontsize=16, fontweight="bold", va="top")

    for ax in axs[:, 1]:
        ax.set_ylabel("")
        ax.tick_params(labelleft=True)

    axs[1, 0].set_ylim(-0.35, 0.35)
    axs[1, 0].set_yticks([-0.2, 0, 0.2])
    axs[1, 1].set_ylim(-0.35, 0.35)
    axs[1, 1].set_yticks([-0.2, 0, 0.2])

    axs[2, 0].set_xlabel("Percent SI")
    axs[2, 1].set_xlabel("Percent SI")

    fig.canvas.draw()
    ax0_pos = axs[0, 0].get_position()
    right_edge = axs[0, 1].get_position().x1
    left_edge = max(0, ax0_pos.x0 - 0.18 * ax0_pos.width)
    img_pos = ax_img.get_position()
    ax_img.set_position([left_edge, img_pos.y0, right_edge - left_edge, img_pos.height])

    if outputDir:
        fig.savefig(outputDir, format="pdf", bbox_inches="tight")
    return fig


def Figure6(panelA_path="./Figure6A.png",
            n_random=1000,
            outputDir=OUTPUT_DIR + "Mekasha_Mascolo_Erill_2025_Fig6.pdf"):
    """
    Figure 6: Genetic code analysis (composite).
    Panel A: schematic (top-left, ~40% width).
    Panel B: %SI vs robustness scatterplot (top-right, ~60% width).
    Panel C: sequence logos — standard (bottom-left) and random (bottom-right).
    """
    import matplotlib.gridspec as gridspec
    import logomaker
    from src.Objects.genetic_code import GeneticCode
    from src.helper_functions.helperFunctions import compute_seq_logo_matrix

    GenCode = GeneticCode()

    # --- Compute Panel B data ---
    GC_perc_SI = GenCode.si_percent()
    GC_robustness = GenCode.robustness()

    rnd_perc_SI_list = []
    rnd_robustness_list = []
    for i in range(n_random):
        if i % 100 == 0:
            print(f"Figure 6B: {i}/{n_random} random codes...")
        GenCode.randomize_code()
        rnd_perc_SI_list.append(GenCode.si_percent())
        rnd_robustness_list.append(GenCode.robustness())

    # Keep one random code for Panel C (right)
    random_code_data = {}
    for message in GenCode.messages:
        codons = list(GenCode.table[GenCode.table.translations == message]['codons'])
        si, c = GenCode._compute_info(codons)
        random_code_data[message] = (codons, c)

    # Reset to standard for Panel C (left)
    GenCode = GeneticCode()
    standard_code_data = {}
    for message in GenCode.messages:
        codons = list(GenCode.table[GenCode.table.translations == message]['codons'])
        si, c = GenCode._compute_info(codons)
        standard_code_data[message] = (codons, c)

    aa_list = sorted(set(standard_code_data.keys()).difference({'Stop'}))
    sorted_messages = aa_list + ['Stop']

    # --- Build composite figure ---
    fig = plt.figure(figsize=(20, 16))
    outer_gs = gridspec.GridSpec(2, 1, figure=fig, height_ratios=[2, 3], hspace=0.25)

    # Top row: Panel A (left) + Panel B (right)
    top_gs = gridspec.GridSpecFromSubplotSpec(1, 2, subplot_spec=outer_gs[0],
                                              width_ratios=[2, 3], wspace=0.3)

    # Panel A — schematic image or spacer
    ax_A = fig.add_subplot(top_gs[0])
    if panelA_path and os.path.exists(panelA_path):
        img_A = mpimg.imread(panelA_path)
        ax_A.imshow(img_A, aspect='equal')
    ax_A.axis("off")
    ax_A.text(0.0, 1.05, "A", transform=ax_A.transAxes,
              fontsize=18, fontweight="bold", va="top")

    # Panel B — scatterplot
    ax_B = fig.add_subplot(top_gs[1])
    ax_B.scatter(rnd_robustness_list, rnd_perc_SI_list, alpha=0.2, label='Random codes')
    ax_B.scatter([GC_robustness], [GC_perc_SI], marker='d', color='red', alpha=0.8, label='Genetic code')
    ax_B.legend()
    ax_B.set_ylabel('Percent SI')
    ax_B.set_xlabel('Robustness')
    min_y = min(50, min(rnd_perc_SI_list))
    ax_B.set_ylim((min_y, 100))
    ax_B.set_xticks([15, 20, 25, 30])
    ax_B.text(-0.12, 1.05, "B", transform=ax_B.transAxes,
              fontsize=18, fontweight="bold", va="top")

    # Bottom row: Panel C — standard logos (left) + random logos (right)
    bottom_gs = gridspec.GridSpecFromSubplotSpec(1, 2, subplot_spec=outer_gs[1],
                                                 wspace=0.15)

    # Helper to plot 3x7 logos into a GridSpec area
    def _plot_logos(parent_spec, code_data, title):
        inner_gs = gridspec.GridSpecFromSubplotSpec(3, 7, subplot_spec=parent_spec,
                                                    hspace=0.4, wspace=0.3)
        for idx, message in enumerate(sorted_messages):
            row, col = divmod(idx, 7)
            ax = fig.add_subplot(inner_gs[row, col])
            seqs, C = code_data[message]
            df = compute_seq_logo_matrix(seqs)
            logomaker.Logo(df, ax=ax)
            ax.bar(3, C, width=0.6, color='darkslategrey')
            ax.axhline(2, color='black', linewidth=0.5, alpha=0.6)
            ax.tick_params(axis='x', labelsize=8)
            ax.tick_params(axis='y', labelsize=8)
            ax.set_xlim(-0.5, 3.5)
            ax.set_xticks([0, 1, 2, 3])
            ax.set_xticklabels(['X', 'Y', 'Z', 'C'])
            ax.set_ylim(0, 3)
            ax.set_ylabel('Bits' if col == 0 else '', fontsize=9)
            ax.set_title(message, fontsize=10)
            if row == 0 and col == 0:
                ax.text(-0.3, 1.45, title, transform=ax.transAxes,
                        fontsize=12, fontweight="bold", va="top")

    _plot_logos(bottom_gs[0], standard_code_data, "Standard genetic code")
    _plot_logos(bottom_gs[1], random_code_data, "Random code")

    # Panel C label
    fig.text(0.02, 0.58, "C", fontsize=18, fontweight="bold", va="top")

    if outputDir:
        fig.savefig(outputDir, format="pdf", bbox_inches="tight")
    return fig


